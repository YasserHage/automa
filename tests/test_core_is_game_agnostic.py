"""Invariant 4, enforced structurally: the core imports no game module.

The claim is about *static* dependency. Game code obviously runs - the core calls it
to enumerate legal actions every turn - but nothing under `automa.core` may name a
particular game, which is what lets a game be added, generated by the Phase 4
compiler, or removed without touching the core at all.

`automa.core.loader` is where that line is drawn: it resolves `automa.games.<name>`
through importlib at runtime. This test is what stops anyone from "simplifying" that
into a plain import.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from _ast_imports import REPO_ROOT, core_modules, offenders

from automa.core.loader import GAMES_PACKAGE, available_games, load_game

FORBIDDEN_PREFIXES = (GAMES_PACKAGE,)


@pytest.mark.parametrize("module", core_modules(), ids=lambda p: p.name)
def test_core_module_imports_no_game(module: Path) -> None:
    found = offenders(module.read_text(encoding="utf-8"), FORBIDDEN_PREFIXES, str(module))
    assert not found, (
        f"{module.relative_to(REPO_ROOT)} imports {found}. The core is game-agnostic: "
        "games are resolved by name at runtime through automa.core.loader "
        "(invariant 4 in CLAUDE.md)."
    )


def test_the_check_actually_catches_a_violation() -> None:
    """Guard the guard."""
    assert offenders("from automa.games import dnup\n", FORBIDDEN_PREFIXES) == [GAMES_PACKAGE]
    assert offenders("import automa.games.nim\n", FORBIDDEN_PREFIXES) == ["automa.games.nim"]
    assert not offenders("import importlib\n", FORBIDDEN_PREFIXES)


def test_the_loader_finds_the_phase_1_games() -> None:
    """Discovery is by enumeration, so a game added later needs no registration."""
    found = available_games()
    assert {"nim", "dnup"} <= set(found), found


def test_loading_an_unknown_game_says_what_is_known() -> None:
    with pytest.raises(Exception) as exc:
        load_game("no_such_game")
    assert "nim" in str(exc.value)
