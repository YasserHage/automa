"""Finding and loading game modules without depending on any of them.

Invariant 4 says "no game module is imported by the core". Read precisely, that is a
statement about *static* dependency: nothing under ``automa.core`` may name a
particular game, so the core cannot be built around one game's shape and cannot stop
working when a game is added or removed. It is not a claim that game code never runs
- it plainly must, since the core enumerates legal actions by calling into it.

This module is where that distinction lives. Games are resolved by name at runtime
through :mod:`importlib`, so the import graph of ``automa.core`` contains no game.
``tests/test_core_is_game_agnostic.py`` enforces the static half by AST-walking every
core module for an ``import automa.games...`` statement, and would fail the build if
one appeared here.
"""

from __future__ import annotations

import importlib
import pkgutil
from types import ModuleType

from automa.core.game import conforms

#: Resolved dynamically, never imported at module scope - see the module docstring.
GAMES_PACKAGE = "automa.games"


class GameLoadError(RuntimeError):
    """A game could not be loaded, or was loaded and does not conform."""


def available_games() -> list[str]:
    """Every game the loader can see, sorted.

    Discovery is by enumeration rather than a hardcoded registry so that a game
    added in a later phase - or generated by the Phase 4 compiler - is picked up by
    the contract tests and the validator without anyone remembering to list it.
    """
    package = importlib.import_module(GAMES_PACKAGE)
    return sorted(
        info.name
        for info in pkgutil.iter_modules(package.__path__)
        if not info.name.startswith("_") and not info.ispkg
    )


def load_game(name: str) -> ModuleType:
    """Import the game called ``name`` and verify it against the contract.

    Refusing a non-conforming module here means every consumer - match loop,
    validator, eval harness - can assume the interface holds. In Phase 4 this is the
    first gate a generated module meets, before it is ever run.
    """
    if not name.isidentifier():
        raise GameLoadError(
            f"{name!r} is not a valid module name. Games are resolved as "
            f"{GAMES_PACKAGE}.<name>; known games: {available_games()}"
        )

    try:
        module = importlib.import_module(f"{GAMES_PACKAGE}.{name}")
    except ModuleNotFoundError as exc:
        raise GameLoadError(
            f"No game named {name!r}. Known games: {available_games()}"
        ) from exc

    problems = conforms(module)
    if problems:
        raise GameLoadError(
            f"{GAMES_PACKAGE}.{name} does not implement the game module contract:\n"
            + "\n".join(f"  - {p}" for p in problems)
        )
    return module
