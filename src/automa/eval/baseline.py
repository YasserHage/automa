"""The baseline: an LLM playing straight from a rules description.

This is what Automa is measured against, so it has to be *good*. `plan.md` is blunt
about the risk - "building the baseline after the final solution is how hackathons are
lost - you unconsciously build a strawman" - and every choice here is aimed at not
doing that:

* **Same model** as the Tactician, forced by `config.DEFAULT_MODELS`.
* **A proper rules brief**, committed at `rules/<game>.md` so anyone can read exactly
  what the baseline was told. For DNUP the brief is generated by a model reading the
  rulebook rather than written by the author of `dnup.py`, who would otherwise be on
  both sides of the comparison.
* **Never penalised for formatting.** It answers with a JSON action; malformed JSON is
  retried through `call_llm`'s feedback loop, so its failures are rule failures.
* **A generous match.** Its proposed action is matched against the legal set exactly,
  then again ignoring the order of list values. The leniency deliberately favours it.

And one thing withheld on purpose: **it is never told a move was illegal.** That
feedback is precisely the corrective intervention the primary metric counts. Supplying
it would erase the measurement and turn the baseline into a slow enumerator.

What it does *not* get is the numbered list of legal actions. That single difference is
the entire hypothesis under test.
"""

from __future__ import annotations

import json
import random
from functools import lru_cache
from pathlib import Path
from typing import Any

from automa.contracts import BaselineMove
from automa.core.game import LABEL, action_shape
from automa.core.match import Decision, TurnContext
from automa.llm import call_llm
from automa.llm.call import LLMCallError

RULES_DIR = Path(__file__).parent / "rules"

SYSTEM = """\
You are playing a board or card game against an opponent. You will be given the rules \
of the game and the current state of play, and you must choose your move.

You are given the rules, not a list of your options: work out for yourself what is \
legal and choose the best legal move. Answer with the move as a JSON object using \
exactly the keys the rules describe, and one short line explaining your choice.\
"""


class MissingBriefError(FileNotFoundError):
    """No rules brief exists for this game."""


@lru_cache(maxsize=8)
def rules_brief(game_name: str) -> str:
    """The committed rules description for a game.

    Cached because it is re-sent on every single turn - the baseline has no memory of
    the rules between calls, which is one of the things being measured.
    """
    path = RULES_DIR / f"{game_name}.md"
    if not path.exists():
        raise MissingBriefError(
            f"No rules brief at {path}. The baseline plays from prose, so a game "
            f"without one cannot be evaluated. Generate it with "
            f"`python -m automa.scripts.build_rules_brief --game {game_name}`."
        )
    return path.read_text(encoding="utf-8")


@lru_cache(maxsize=8)
def action_format(game_name: str) -> str:
    """How to write a move for this game, derived from the module itself.

    Kept out of the prose brief and generated from real enumerated actions, so the
    format shown to the baseline cannot drift from the format the harness matches
    against. A brief that documented a stale key would make the baseline fail for a
    reason that has nothing to do with the rules.

    Shapes are collected by walking a *reference* match, never the position being
    asked about, so no legal answer is leaked. Walking rather than reading the opening
    position matters: at DNUP's opening the table is empty, so only `play` and
    `rotate` exist, and a baseline that had never been shown the keys for `take` or
    `add` would fail on **formatting** when it wanted one - the precise failure this
    whole design is meant to make impossible.
    """
    import random as _random

    from automa.core.loader import load_game

    game = load_game(game_name)
    state = game.initial_state(0)
    rng = _random.Random("action-format")

    by_shape: dict[tuple[str, ...], dict[str, Any]] = {}
    for _ in range(40):
        if game.is_terminal(state):
            break
        actions = game.legal_actions(state)
        for action in actions:
            by_shape.setdefault(tuple(sorted(_without_label(action))), action)
        state = game.apply(state, rng.choice(actions))

    lines = [
        "## How to express your move",
        "",
        "Reply with `action_json`: a single JSON object using exactly these keys.",
        "The shapes available in this game are:",
        "",
    ]
    for shape, example in sorted(by_shape.items()):
        sample = json.dumps(_without_label(example))
        lines.append(f"- keys `{list(shape)}` - for example `{sample}`")
    lines += [
        "",
        "These examples come from the opening position and are illustrations of the "
        "*format* only - they are not suggestions, and may not be legal now.",
    ]
    return "\n".join(lines)


def _without_label(action: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in action.items() if k != LABEL}


def _loose(action: dict[str, Any]) -> dict[str, Any]:
    """A comparison key that ignores the order of list values.

    So a baseline answering ``cards: [18, 10]`` is not marked illegal for a set the
    module happens to enumerate as ``[10, 18]``. Ordering carries no meaning in either
    game's action schema, and where it is ambiguous the benefit goes to the baseline.
    """
    return {
        k: sorted(v, key=repr) if isinstance(v, list) else v
        for k, v in _without_label(action).items()
    }


def match_action(proposed: Any, actions: list[dict[str, Any]]) -> int | None:
    """Index of the legal action the proposal denotes, or ``None`` if it denotes none.

    Exact match first, then the order-insensitive one. Returns ``None`` for anything
    that is not a JSON object at all, which counts as an illegal move rather than a
    format error - the format was already validated upstream.
    """
    if not isinstance(proposed, dict):
        return None
    stripped = _without_label(proposed)
    for i, action in enumerate(actions):
        if _without_label(action) == stripped:
            return i
    loose = _loose(proposed)
    for i, action in enumerate(actions):
        if _loose(action) == loose:
            return i
    return None


@lru_cache(maxsize=8)
def _known_shapes(game_name: str) -> frozenset[tuple[tuple[str, str], ...]]:
    """Every action signature this game can produce, from the reference playout.

    Taken from the *game*, never from the position being asked about, so telling the
    baseline its answer is malformed leaks nothing about what is legal right now.
    """
    from automa.core.loader import load_game

    game = load_game(game_name)
    state = game.initial_state(0)
    rng = random.Random("action-format")
    shapes: set[tuple[tuple[str, str], ...]] = set()
    for _ in range(40):
        if game.is_terminal(state):
            break
        actions = game.legal_actions(state)
        shapes.update(action_shape(a) for a in actions)
        state = game.apply(state, rng.choice(actions))
    return frozenset(shapes)


def _parse(result: Any) -> Any:
    """Parse the model's action JSON, raising so `call_llm` retries with feedback."""
    raw = result.parsed.action_json.strip()
    if raw.startswith("```"):
        # Fenced code is a formatting habit, not a rules error. Strip it rather than
        # counting it against the baseline.
        raw = raw.strip("`")
        raw = raw[raw.find("\n") + 1:] if "\n" in raw else raw
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"action_json is not valid JSON ({exc}). Reply with a single JSON object "
            "using the keys from the rules."
        ) from exc


def _check_well_formed(game_name: str, proposed: Any) -> None:
    """Reject an action that is not *expressible* in this game, so it can be retried.

    The line this draws matters for fairness, and it is drawn deliberately:

    * **Is this a well-formed action for this game?** A formatting question. Retried
      with feedback, because the baseline must never lose on encoding.
    * **Is this action legal right now?** A rules question. Never retried, because
      being told is exactly the corrective intervention the primary metric counts.

    The case that forced the distinction: given a Nim board rendered as
    ``A: oo (2)  B: ooo (3)``, the baseline answered ``{"heap": "B", "count": 2}``.
    It had read the position correctly and picked a real move - it just wrote the
    heap the way the *display* names it rather than as the integer index the schema
    wants. Scoring that as a rules failure would have understated the baseline
    exactly the way `plan.md` warns against.

    Signatures come from the game's whole action vocabulary, not from the current
    legal set, so this feedback reveals nothing about the position.
    """
    if not isinstance(proposed, dict):
        raise ValueError(
            f"action_json must be a JSON object, got {type(proposed).__name__}."
        )
    known = _known_shapes(game_name)
    if action_shape(proposed) in known:
        return
    expected = "; ".join(
        "{" + ", ".join(f'"{k}": <{t}>' for k, t in shape) + "}" for shape in sorted(known)
    )
    raise ValueError(
        f"{json.dumps(proposed)} is not a well-formed action for this game. "
        f"Check the key names and value types. Valid shapes are: {expected}. "
        "Numeric fields are indices or counts, never names or letters."
    )


def _validate_format(game_name: str):
    def _validate(result: Any) -> None:
        _check_well_formed(game_name, _parse(result))

    return _validate


def baseline_decider(*, max_attempts: int = 3, seed: int | None = None):
    """Build a decider that plays from prose alone.

    Returns an index like any decider, but derives it from its own proposed action
    rather than from a list it was shown. When the proposal is not legal, the harness
    records an intervention and substitutes a random legal action so the match can
    continue - which is how one match yields both "turns before the first
    intervention" and "illegal actions per match".
    """
    rng = random.Random(seed)

    def decide(ctx: TurnContext) -> Decision:
        prompt = (
            f"{rules_brief(ctx.game.NAME)}\n\n"
            f"{action_format(ctx.game.NAME)}\n\n"
            f"--- Current state ---\n{ctx.view()}\n\n"
            f"You are {ctx.player}. Choose your move."
        )
        try:
            result = call_llm(
                agent="baseline",
                system=SYSTEM,
                messages=[{"role": "user", "content": prompt}],
                output_format=BaselineMove,
                # Validates *format* only - parseable JSON, and an action shape this
                # game can actually express. Legality is deliberately not checked
                # here: telling the baseline its move was illegal is the intervention
                # being measured, so it must happen after the answer is final.
                validate=_validate_format(ctx.game.NAME),
                max_attempts=max_attempts,
                max_tokens=2048,
                trajectory=ctx.trajectory,
                tags={"game": ctx.game.NAME, "turn": ctx.turn, "ply": ctx.ply},
            )
        except LLMCallError as exc:
            return _substitute(ctx, rng, reason=f"model unreachable: {exc}", fallback=True)

        proposed = _parse(result)
        index = match_action(proposed, ctx.actions)
        if index is None:
            return _substitute(
                ctx,
                rng,
                reason=f"proposed an illegal action: {json.dumps(proposed)}",
                fallback=False,
                justification=result.parsed.justification,
            )
        return Decision(index=index, justification=result.parsed.justification)

    return decide


def _substitute(
    ctx: TurnContext,
    rng: random.Random,
    *,
    reason: str,
    fallback: bool,
    justification: str | None = None,
) -> Decision:
    """Stand in for a move that cannot be played, and put why on the record.

    ``fallback`` separates the two reasons this happens. An unreachable model is an
    outage and says nothing about the baseline's grasp of the rules; an illegal
    proposal is exactly what the primary metric counts. Recording them in one bucket
    would let a bad afternoon on the provider masquerade as a rules failure.
    """
    if ctx.trajectory is not None:
        ctx.trajectory.emit(
            "core_event",
            event="baseline_fallback" if fallback else "baseline_intervention",
            ply=ctx.ply,
            turn=ctx.turn,
            reason=reason,
            legal_action_count=len(ctx.actions),
            note=(
                "Model unreachable; played a random legal action."
                if fallback
                else "Illegal move proposed. A human would have to correct this. "
                "Substituted a random legal action so the match can continue."
            ),
        )
    return Decision(
        index=rng.randrange(len(ctx.actions)),
        justification=justification or "(substituted)",
        fallback=fallback,
        intervention=not fallback,
    )
